def _snapshot_row(t: TableRef, target_schema: str, identifier_case="lowercase") -> str:
    """One TABLES entry, mapping source names to their Lakebase targets (matching
    the plan). The scanned primary key's leading column rides along as the
    partition-column candidate for the range-partitioned read."""
    dst_schema = map_schema(t.schema_name, target_schema, identifier_case)
    dst_table = map_object(t.table_name, identifier_case)
    part = f'"{t.primary_key[0]}"' if t.primary_key else "None"
    return f'    ("{t.schema_name}", "{t.table_name}", "{dst_schema}", "{dst_table}", {part})'


def _post_load_rows(statements: list[PostLoadStatement]) -> str:
    """POST_LOAD entries for one phase. repr() keeps arbitrary SQL (quotes, $$
    bodies, newlines) a valid Python literal. Trigger SQL is sanitized here — at
    emit time — so a stale/hand-edited plan (schema-qualified trigger name, no
    OR REPLACE) still applies cleanly regardless of when it was built."""
    rows = []
    for s in statements:
        if not s.sql.strip():
            continue
        sql = sanitize_trigger_sql(s.sql) if s.kind == "trigger" else s.sql
        rows.append(f"    ({s.name!r},\n     {sql!r})")
    return ",\n".join(rows)


def _snapshot(req: DataGenRequest) -> Artifact:
    rows = ",\n".join(
        _snapshot_row(t, req.target_schema, req.identifier_case) for t in req.tables
    )
    code = _SNAPSHOT.replace("__HEADER__", _render_header(req)).replace("__TABLES__", rows)
    return Artifact(
        name="Snapshot load (PySpark)",
        filename="01_snapshot_load.py",
        language="python",
        description="Parallel full copy of each selected table from the source straight into the "
        "Lakebase Postgres tables the schema & code plan created, via Postgres COPY.",
        code=code,
    )


def _post_load_notebook(
    req: DataGenRequest, seq: int, task_key: str, title: str, statements: list[PostLoadStatement]
) -> Artifact:
    code = (
        _POST_LOAD_NB.replace("__PG_HEADER__", _render_pg_header(req))
        .replace("__POST_LOAD__", _post_load_rows(statements))
        # Title first — it also appears inside __PHASE_LOWER__'s source line.
        .replace("__PHASE_TITLE__", title)
        .replace("__PHASE_LOWER__", title[0].lower() + title[1:])
    )
    return Artifact(
        name=f"Post-load — {title}",
        filename=f"{seq:02d}_post_load_{task_key}.py",
        language="python",
        description=f"Applies the plan's {title.lower()} after the snapshot — one idempotent "
        "statement per transaction, with per-item progress; a distinct job task so failures "
        "surface per type and can be repaired alone.",
        code=code,
    )


def post_load_artifacts(req: DataGenRequest) -> list[Artifact]:
    """One post-load notebook per object type that has statements, in the order
    the job chains them (constraints → indexes → foreign keys → triggers). The
    task_key is the artifact filename stem, which job_offload turns into the job
    task graph."""
    arts: list[Artifact] = []
    seq = 2  # 01_snapshot_load is the first notebook
    for task_key, title, kinds in _POST_LOAD_PHASES:
        stmts = [s for s in req.post_load_sql if s.kind in kinds and s.sql.strip()]
        if not stmts:
            continue
        arts.append(_post_load_notebook(req, seq, task_key, title, stmts))
        seq += 1
    return arts


def generate(req: DataGenRequest) -> list[Artifact]:
    """Async-mode notebooks: the PySpark snapshot loader first, then one post-load
    DDL notebook per object type (constraints, indexes, foreign keys, triggers) —
    each a separate, dependency-chained job task."""
    return [_snapshot(req), *post_load_artifacts(req)]
