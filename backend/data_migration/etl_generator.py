"""Generates a runnable PySpark **snapshot** notebook: source -> Lakebase (Postgres).

Async mode is a one-off snapshot. The schema & code migration plan (the same plan
Sync mode applies) creates the target tables in Lakebase Postgres; this generated
notebook reads each selected source table with Spark's named ``sqlserver``
connector (range-partitioned on the scanned primary key when possible) and streams
it straight into the plan-created table with Postgres ``COPY .. FROM STDIN`` from
every partition — the same protocol (and type fidelity) Sync mode uses, with no
staging table or ``INSERT .. SELECT CAST(..)`` double write. Tables load
concurrently on a thread pool so a multi-node cluster stays busy end to end.
Source columns Spark can't read raw (``sql_variant``, ``hierarchyid``, spatial —
UNRECOGNIZED_SQL_TYPE) are converted to text by SQL Server inside the SELECT
list, matching the ``text`` columns the plan creates for them.
Running it on Databricks (serverless or classic job compute) lets the copy scale
out beyond the in-app loader — there is no Delta landing, no synced table and no
CDC.

The generated code reads both the source and the Lakebase passwords from a
Databricks secret scope at runtime (never embedded). It's emitted as text for the
user to review, drop into a notebook/job, and run — the accelerator does not
execute it for them.

Templates are plain strings with ``__TOKEN__`` placeholders (not f-strings) so the
generated Python can contain real f-strings/braces without escaping games.
"""
